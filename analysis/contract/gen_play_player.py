#!/usr/bin/env python3
"""Embed the accepted general player candidate without replacing the old frame chain.

Usage: gen_play_player.py PLAYER.cfg BOUNDS.g ENEMY.cfg LEANROOT [MODULE]
The bounds are this player's converged bounds, not yet a shared frame invariant.
Every result is rechecked by native_decide; no generated table is trusted.
"""
import json
import sys
from pathlib import Path

player, bounds, enemy, root = map(Path, sys.argv[1:5])
module = sys.argv[5] if len(sys.argv) > 5 else "PlayPlayer"
if not module.isidentifier() or not module.isascii():
    raise SystemExit("MODULE must be an ASCII identifier")
skip = {'global', 'assume', 'saveg', 'max', 'maxboxes', 'next', 'dump', 'dumpc',
        'watch', 'promote', 'gwiden', 'nocheck', 'nogrow'}

def config(path):
    lines = [line.strip() for line in path.read_text().splitlines()
             if line.split() and line.split()[0] not in skip]
    # The same buffer assumptions are present in the converged global bounds.
    lines += ['assume 300 00-34', 'assume 340 00-21', 'nogrow',
              'max 10000000', 'promote FFFFFF']
    return '\n'.join(lines)

btext = '|'.join(' '.join(w[1:]) for line in bounds.read_text().splitlines()
                 if (w := line.split()) and w[0] == 'global' and w[2] != 'top')
# json's quoted ASCII string is also a Lean string literal for these configs.
def quote(s):
    return json.dumps(s)

(root / f'Smb/{module}Data.lean').write_text(f'''import Smb.Abs.Config

/-!
General player region during normal 1-1 control. Generated by
`analysis/contract/gen_play_player.py` from the converged player bounds.
These are not yet shared bounds for a complete gameplay frame.
-/
namespace Smb.Abs.{module}

def boundsText : String := {quote(btext)}

def G : Global := Id.run do
  let mut g : Global := Array.replicate 0x800 VS.top
  for line in boundsText.splitOn "|" do
    match line.splitOn " " with
    | a :: vs => g := g.set! (Config.hx a) (Config.parseVals vs)
    | [] => pure ()
  return g

def player : Config.C := Config.parse {quote(config(player))}
def enemy : Config.C := Config.parse {quote(config(enemy))}

/-- Accept the player table and its enemy-entry link. Normal-control exits stay open. -/
def accepted (prg : ByteArray) : Bool :=
  player.linkedE G prg [(0xAF01, enemy.entries)]
    [0x8082, 0x8085, 0x8087, 0x808A, 0x808C]

end Smb.Abs.{module}
''')
(root / f'Smb/Routine/{module}.lean').write_text(f'''import Smb.Game
import Smb.{module}Data

/-! A checked general player-region table, not a whole-frame invariant. -/
namespace Smb.Routine.{module}

theorem accepted : Smb.Abs.{module}.accepted Smb.prg = true := by native_decide

end Smb.Routine.{module}
''')
