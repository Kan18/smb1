#!/usr/bin/env python3
"""Write the Lean modules for the launch phase's regions, from launch_regions.py's configs. usage: gen_launch.py CONFIGDIR LEANROOT
Nothing in them is trusted: each theorem has the checker accept a table, and its exits lie in the next region's entries."""
import sys
cdir, root = sys.argv[1:3]
NAMES = {'H': 'the NMI handler up to the game logic', 'Q': 'the game mode dispatch up to `PlayerCtrlRoutine`', 'R': 'after `PlayerCtrlRoutine`, up to the enemy loop', 'E': 'the enemy loop',
         'T': 'the engine after the enemy loop', 'A': '`SaveAB`', 'B': 'the end of the engine', 'Z': 'the end of the handler, the idle loop, and the next NMI up to `$808F`'}
LINKS = {'H': [('8175', 'Q'), ('8178', 'Z')], 'Q': [], 'R': [('AF01', 'E')], 'E': [('AF10', 'T')], 'T': [('AF67', 'A')], 'A': [('AF6B', 'B')], 'B': [('8178', 'Z')], 'Z': [('808F', 'H')]}
PRE = '[0x8082, 0x8085, 0x8087, 0x808A, 0x808C]'
# Exits a region can take with no next region: `Q` ends at the routine, `T` when the timer runs out. No state reaches any other, so each must have an empty table.
OPEN = {'Q': 'B0E9', 'T': 'B79A'}
bounds, texts, done = {}, {}, []
# Which addresses the region's table must have nothing at. Only `Z` reaches the closing sequence and the idle loop, only `Q` the routine, only `T` the timer's end.
def emptiesOf(r):
    return '(' + ('doneList' if r == 'Z' else 'preList ++ idleList ++ doneList') + {'Q': ' ++ timeList', 'T': ' ++ entryList', 'R': ' ++ timeList ++ entryList ++ saveList', 'E': ' ++ timeList ++ entryList ++ saveList'}.get(r, ' ++ timeList ++ entryList') + ')'
for r in NAMES:
    keep = []
    for line in open(f'{cdir}/{r}.cfg'):
        w = line.split()
        if w and w[0] in ('global', 'assume'):
            bounds[int(w[1], 16)] = ' '.join(w[2:])
        if w and w[0] == 'exit' and w[1] != OPEN.get(r) and w[1] not in [pc for pc, _ in LINKS[r]]:
            done.append('0x' + w[1]) if '0x' + w[1] not in done else None
        if not w or w[0] in ('global', 'saveg', 'max', 'next', 'dump', 'dumpc', 'watch', 'promote', 'gwiden', 'maxboxes'):
            continue
        keep.append(line.strip())
    keep += ['nogrow', 'max 10000000', 'promote FFFFFF']
    texts[r] = '\\n'.join(keep)
btext = '|'.join(f'{a:x} {v}' for a, v in sorted(bounds.items()))
defs = '\n\n'.join(f'''/-- {NAMES[r]} -/
def text{r} : String := "{texts[r]}"
def {r} : Config.C := Config.parse text{r}''' for r in NAMES)
linked = '\n'.join(f'def linked{r} (prg : ByteArray) : Bool := {r}.linkedE G prg [' + ', '.join(f'(0x{pc}, {n}.entries)' for pc, n in LINKS[r]) + f'] {emptiesOf(r)}' for r in NAMES)
open(f'{root}/Smb/Abs/LaunchData.lean', 'w').write(f'''import Smb.Abs.Config

/-!
# A frame of the launch at the start of 1-1, in regions

Every enemy slot is empty, the screen hasn't scrolled and the parser is idle. `PlayerCtrlRoutine` isn't here: `Smb.Routine.ModelFrame` has it, so `Q` ends at its entry and `R` starts at its end. Each region's boxes at its exit must lie in the next region's entry boxes.

Generated by `analysis/contract/gen_launch.py`. Nothing here is trusted: `Smb.Routine.Launch*` has the checker accept each region's table.
-/
namespace Smb.Abs.LaunchPhase

def boundsText : String := "{btext}"

/-- The shared bounds; every other cell is unconstrained. -/
def G : Global := Id.run do
  let mut g : Global := Array.replicate 0x800 VS.top
  for line in boundsText.splitOn "|" do
    match line.splitOn " " with
    | a :: vs => g := g.set! (Config.hx a) (Config.parseVals vs)
    | [] => pure ()
  return g

{defs}

/-- The closing sequence's addresses, which only `Z` reaches. -/
def preList : List UInt16 := {PRE}

def idleList : List UInt16 := [0x8057]
def timeList : List UInt16 := [0xB79A]
def entryList : List UInt16 := [0xB0E9]
def saveList : List UInt16 := [0xAF67]

/-- Where normal control ends. No state in any region reaches one, which each `linked` shows. -/
def doneList : List UInt16 := [{', '.join(done)}]

{linked}

end Smb.Abs.LaunchPhase
''')
for r in NAMES:
    open(f'{root}/Smb/Routine/LaunchPhase{r}.lean', 'w').write(f'''import Smb.Game
import Smb.Abs.LaunchData

/-! The checker accepts the table for {NAMES[r]}, during the launch. -/
namespace Smb.Routine.LaunchPhase

theorem linked{r} : Smb.Abs.LaunchPhase.linked{r} Smb.prg = true := by native_decide

end Smb.Routine.LaunchPhase
''')
print(len(bounds), 'bounds')
