#!/usr/bin/env python3
"""Write a region's Lean module from an smbabs config and the bounds its run saved.
usage: gen_region.py NAME CONFIG SAVED.g OUT.lean "DOC"
The module holds the config as text, with the bounds fixed. Nothing in it is trusted: a theorem has the checker accept the table."""
import sys

name, cfg, saved, out, doc = sys.argv[1:6]
keep = []
for line in open(cfg):
    w = line.split()
    if not w or w[0] in ('global', 'saveg', 'max', 'dump', 'dumpc', 'watch', 'nogrow', 'promote', 'gwiden', 'next', 'exitonly') or line.startswith('#'):
        continue
    keep.append(line.strip())
tracked = []
for line in open(saved):
    w = line.split()
    if not w:
        continue
    if w[0] == '#' and w[1] == 'promoted':
        tracked = [x.strip('[], ') for x in w[2:] if x.strip('[], ')]
    if w[0] == 'global' and w[2] != 'top':
        keep.append(line.strip())
keep += ['track ' + t for t in tracked]
keep += ['nogrow', 'max 10000000', 'promote FFFFFF']
text = '\\n'.join(keep)
open(out, 'w').write(f'''import Smb.Abs.Config

/-!
{doc}

Generated by `analysis/engine_bounds/gen_region.py`. Nothing here is trusted: a theorem has the checker accept the table computed from it.
-/
namespace Smb.Abs.{name}

def text : String := "{text}"

def conf : Config.C := Config.parse text

end Smb.Abs.{name}
''')
print(len(keep), 'lines')
