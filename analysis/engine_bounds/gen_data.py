#!/usr/bin/env python3
"""Write lean/Smb/Abs/EngineTailData.lean from a saved smbabs run. usage: gen_data.py SAVED.g OUT.lean TRACKED...
The module's header, entry box and hints are kept here, so regenerating only changes the bounds."""
import sys

saved, out, tracked = sys.argv[1], sys.argv[2], sys.argv[3:]
bounds = []
for line in open(saved):
    w = line.split()
    if w and w[0] == 'global' and w[2] != 'top':
        bounds.append(w[1] + ' ' + ' '.join(w[2:]))
open(out, 'w').write(f'''import Smb.Abs.Fix

/-!
# Bounds for the engine's tail, after the enemy loop

From `$AF10` (after the enemy loop) to `SaveAB` `$AF67`, with RAM bounds that came out of a run of `smbabs`: seeded from the
values in the TAS's player-controlled frames of 1-1 (frames 194 to 1285), then widened wherever the code writes outside them.
Nothing here is trusted: `Smb.Routine.EngineTail` has the checker accept the table computed from it.
Generated by `analysis/engine_bounds/gen_data.py`.
-/
namespace Smb.Abs.EngineTail

/-- `addr v v v` per bounded cell, in hex; every other cell is unconstrained. -/
def boundsText : String := "{'|'.join(bounds)}"

def hexOf (s : String) : Nat := s.foldl (fun n c =>
  n * 16 + (if c.isDigit then c.toNat - 48 else (c.toLower.toNat - 97 + 10))) 0

/-- The global bounds. -/
def bounds : Global := Id.run do
  let mut g : Global := Array.replicate 0x800 VS.top
  for line in boundsText.splitOn "|" do
    match line.splitOn " " with
    | a :: vs => g := g.set! (hexOf a) (.set (vs.map fun v => UInt8.ofNat (hexOf v)))
    | [] => pure ()
  return g

def exit (a : UInt16) : Bool := a == 0xAF67

/-- Mario's X position and sub-pixel and the screen edges: the code here must not write them. -/
def prot (i : UInt16) : Bool :=
  i == 0x86 || i == 0x6D || i == 0x400 || i == 0x71A || i == 0x71B || i == 0x71C || i == 0x71D

def tracked : List UInt16 := [{', '.join('0x' + t for t in tracked)}]

def entry : Box :=
  {{ pc := 0xAF10, s := 0xF9, a := .top, x := .top, y := .top, p := .set [0x27, 0x67],
     cells := [(0x300, .set [0, 7, 0xA, 0xD, 0xE, 0x15, 0x18, 0x1C, 0x1F, 0x25, 0x2A])] }}

def cfg (rom : UInt16 → UInt8) : Cfg :=
  {{ rom, exit, prot, g := bounds,
     track := fun i => i ≤ 0xF || i == 0x300 || tracked.contains i,
     splitY := fun a => (0x89EF ≤ a && a ≤ 0x89F9) || (0x8600 ≤ a && a ≤ 0x8622),
     splitCells := [0, 3], maxSteps := 500000, promoteAfter := 1000000 }}

def table (prg : ByteArray) : Table := (fixpoint (cfg (romOf prg)) [entry]).table

/-- One computation of the table, checked as an invariant containing the entry box. -/
def accepted (prg : ByteArray) : Bool :=
  let T := table prg
  check (romOf prg) exit prot bounds T && entryIn bounds T entry

/-- The bound on `Player_X_Speed` is the speed limit's. -/
def speedBounded : Bool := allBytes.all fun v => !(gAt bounds 0x57).mem v || v ≤ 0x28 || 0xD8 ≤ v

end Smb.Abs.EngineTail
''')
print(len(bounds), 'bounds')
