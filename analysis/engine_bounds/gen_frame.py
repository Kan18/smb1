#!/usr/bin/env python3
"""Write the frame's Lean modules from the regions' configs and shared bounds. usage: gen_frame.py CONFIGDIR BOUNDS.g LEANROOT [REGIONS]
REGIONS, default HPETAZ, picks the regions; a link to a region left out is dropped, and its address has to count as an end of the run in the theorem that uses them.
Writes Smb/Abs/FrameData.lean and one Smb/Routine/Frame<R>.lean per region. Nothing in them is trusted: each theorem has the checker accept a table."""
import sys
cdir, bfile, root = sys.argv[1:4]
chosen = sys.argv[4] if len(sys.argv) > 4 else 'HPETAZ'
NAMES = {'H': 'the NMI handler up to the game logic', 'P': 'the game mode dispatch, the player routines and the fireballs', 'E': 'the enemy loop',
         'T': 'the engine after the enemy loop', 'A': 'the area parser', 'Z': 'the end of the handler, the idle loop, and the next NMI up to `$808F`'}
LINKS = {'H': [('8175', 'P'), ('8178', 'Z')], 'P': [('AF01', 'E')], 'E': [('AF10', 'T')], 'T': [('AF67', 'A')], 'A': [('8178', 'Z')], 'Z': [('808F', 'H')]}
DONE = '91BA 9277 B0D5 B1B8 B27A B8AA D948 DDFC DE75 DE86 DF01 FAEF 8031 82CB 82F2 8483 91E5 9260 927E DE15 82CE 82FD 845D 8475 874E 905D 90C8 91E0 9233 925A 9279 B218 D009 DE10'.split()
NAMES = {r: n for r, n in NAMES.items() if r in chosen}
LINKS = {r: [(pc, n) for pc, n in LINKS[r] if n in chosen] for r in NAMES}
PRE = '[0x8082, 0x8085, 0x8087, 0x808A, 0x808C]'
bounds = []
for line in open(bfile):
    w = line.split()
    if len(w) > 2 and w[0] == 'global' and w[2] != 'top' and int(w[1], 16) != 0xE:
        bounds.append(w[1] + ' ' + ' '.join(w[2:]))
bounds.append('000e 08')
texts = {}
for r in NAMES:
    keep = []
    for line in open(f'{cdir}/{r}.cfg'):
        w = line.split()
        if not w or w[0] in ('global', 'saveg', 'max', 'next', 'dump', 'dumpc', 'watch', 'promote', 'gwiden', 'maxboxes'):
            continue
        keep.append(line.strip())
    keep += ['nogrow', 'max 10000000', 'promote FFFFFF']
    texts[r] = '\\n'.join(keep)
defs = '\n\n'.join(f'''/-- {NAMES[r]} -/
def text{r} : String := "{texts[r]}"
def {r} : Config.C := Config.parse text{r}''' for r in NAMES)
linked = '\n'.join(f'def linked{r} (prg : ByteArray) : Bool := {r}.linkedE G prg [' + ', '.join(f'(0x{pc}, {n}.entries)' for pc, n in LINKS[r]) + '] ' + ('[]' if r == 'Z' else PRE) for r in NAMES)
done = ' || '.join(f'a == 0x{d}' for d in DONE)
open(f'{root}/Smb/Abs/FrameData.lean', 'w').write(f'''import Smb.Abs.Config

/-!
# A gameplay frame, in regions

The regions of a frame during normal control in 1-1 and the RAM bounds they share. Each region's boxes at its exit must lie in the next region's entry boxes. The bounds
started from values in the TAS's player-controlled frames and were widened until the code keeps them.

Generated by `analysis/engine_bounds/gen_frame.py`. Nothing here is trusted: `Smb.Routine.Frame` has the checker accept each region's table.
-/
namespace Smb.Abs.Frame

def boundsText : String := "{'|'.join(bounds)}"

/-- The shared bounds; every other cell is unconstrained. -/
def G : Global := Id.run do
  let mut g : Global := Array.replicate 0x800 VS.top
  for line in boundsText.splitOn "|" do
    match line.splitOn " " with
    | a :: vs => g := g.set! (Config.hx a) (.set (vs.map fun v => UInt8.ofNat (Config.hx v)))
    | [] => pure ()
  return g

{defs}

{linked}

/-- The stores that end normal control: `$0E` takes another value, or `OperMode_Task` changes. -/
def done (a : UInt16) : Bool := {done}

end Smb.Abs.Frame
''')
for r in NAMES:
    open(f'{root}/Smb/Routine/Frame{r}.lean', 'w').write(f'''import Smb.Game
import Smb.Abs.FrameData

/-! The checker accepts the table for {NAMES[r]}. -/
namespace Smb.Routine.Frame

theorem linked{r} : Smb.Abs.Frame.linked{r} Smb.prg = true := by native_decide

end Smb.Routine.Frame
''')
print(len(bounds), 'bounds')
