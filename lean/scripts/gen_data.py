"""Generate the Lean cartridge and movie modules for the target TAS."""
import hashlib
import re
import sys
from pathlib import Path

import fm2

ROM_MD5 = "8e3630186e35d477231bf8fd50e54cdd"
TAS_INPUT_SHA256 = "f49285e74d7b5e39214aa1669f8ad237592e3c3da8f64d3c999cd5e3e0204990"


def proof_rom(prg):
    """Expand address/length references to ordinary Lean list and array literals."""
    refs = {"smbPrg%": set(), "smbPrgArray%": set()}
    pattern = re.compile(r"\b(smbPrg(?:Array)?%)\s+(0x[0-9a-fA-F]+)\s+([0-9]+)")
    smb = Path(__file__).resolve().parents[1] / "Smb"
    for path in smb.rglob("*.lean"):
        if (smb / "Data") in path.parents:
            continue
        for syntax, address, length in pattern.findall(path.read_text()):
            start, size = int(address, 16) - 0x8000, int(length)
            if not (0 <= start and 0 < size and start + size <= len(prg)):
                raise SystemExit(f"{path}: PRG excerpt {address} {length} is outside ROM")
            refs[syntax].add((start, size, address, length))

    lines = [
        "-- Generated by scripts/gen_data.py from the supplied cartridge.",
        "-- Expand to literals so the routine proofs can simplify individual bytes.",
        "import Lean",
        "",
        "set_option maxRecDepth 2048",
    ]
    for syntax, prefix in (("smbPrg%", "["), ("smbPrgArray%", "#[")):
        lines += ["", f'syntax "{syntax} " num num : term']
        if refs[syntax]:
            lines.append("macro_rules")
        for start, size, address, length in sorted(refs[syntax]):
            values = [f"0x{value:02X}" for value in prg[start:start + size]]
            rows = [", ".join(values[i:i + 16]) for i in range(0, size, 16)]
            lines.append(f"  | `({syntax} {address} {length}) =>")
            lines.append(f"    `({prefix}" + ",\n      ".join(rows) + "])")
    return "\n".join(lines) + "\n"


if len(sys.argv) != 4:
    raise SystemExit("usage: gen_data.py ROM MOVIE OUT_DIR")

rom_path, movie_path, out_dir = map(Path, sys.argv[1:])
raw = rom_path.read_bytes()
if (
    len(raw) != 16 + 0x8000 + 0x2000
    or raw[:6] != b"NES\x1a\x02\x01"
    or raw[6] >> 4 != 0
    or raw[6] & 0x0D != 1
    or raw[7] & 0xF3 != 0
    or (
        raw[7] & 0x0C != 0
        and not (raw[7] & 0x0C == 8 and raw[8] == 0 and raw[9] == 0)
    )
):
    raise SystemExit("expected a vertical-mirroring NROM cartridge with 32 KiB PRG and 8 KiB CHR")

body = raw[16:]
md5 = hashlib.md5(body).hexdigest()
if md5 != ROM_MD5:
    raise SystemExit("cartridge data does not match Super Mario Bros. (World)")

frames, checksum = fm2.load(movie_path)
if checksum != fm2.rom_checksum(rom_path):
    raise SystemExit("movie ROM checksum does not match the cartridge")
if frames[0] != (1, 0, 0) or any(cmd or p2 for cmd, _, p2 in frames[1:]):
    raise SystemExit("expected an idle reset row, followed by controller-1 inputs with no commands")

# Preserve the idle first row. Smb.Tas drops it when aligning the replay.
pads = bytes(p1 for _, p1, _ in frames)
if hashlib.sha256(pads).hexdigest() != TAS_INPUT_SHA256:
    raise SystemExit("controller inputs do not match TASVideos publication #1715")

excerpts = proof_rom(body[:0x8000])
out_dir.mkdir(parents=True, exist_ok=True)
(out_dir / "ProofRom.lean").write_text(excerpts)
(out_dir / "Rom.lean").write_text(f"""-- Generated by scripts/gen_data.py.
-- PRG+CHR MD5 (as in FM2 movie headers): {md5}
namespace Smb.Data

/-- PRG ROM (32 KiB) followed by CHR ROM (8 KiB), hex-encoded. Mapper 0, vertical mirroring. -/
def romHex : String :=
  "{body.hex()}"

end Smb.Data
""")
(out_dir / "Tas.lean").write_text(f"""-- Generated by scripts/gen_data.py from the inputs of TASVideos publication #1715.
-- Controller-1 input SHA-256, with the initial idle row: {TAS_INPUT_SHA256}
namespace Smb.Data

/-- Controller-1 byte for each of the movie's {len(pads)} rows (bit 0 = A, 1 = B, 2 = Select,
3 = Start, 4 = Up, 5 = Down, 6 = Left, 7 = Right). Controller 2 is idle throughout. -/
def tasHex : String :=
  "{pads.hex()}"

end Smb.Data
""")
print(f"Generated Lean inputs for {len(pads)} movie rows ({len(pads) - 1} aligned frames).")
