"""Generate Smb/RefineExec.lean: one simulation theorem per opcode, then their union.

Separate theorems let Lean check the 256 cases in parallel.
usage: python3 scripts/gen_exec_sim.py > Smb/RefineExec.lean
"""
ops = range(256)
out = ['''-- Generated by scripts/gen_exec_sim.py. Do not edit.
import Smb.Refine

/-! Every opcode's execution on the full NES simulates its execution on the plain machine. -/
namespace Smb.Sim

set_option maxHeartbeats 1000000
set_option maxRecDepth 20000
''']
for op in ops:
    out.append(f'theorem exec_{op:02x} : Sim (CPU.exec (σ := NES) 0x{op:02X}) (CPU.exec (σ := Plain) 0x{op:02X}) := by sim_tac')
arms = '\n'.join(f'  | {op}, _ => exact exec_{op:02x}' for op in ops)
out.append(f'''
/-- Case analysis on the opcode's underlying number. (An `rcases` over a 256-way
disjunction is ~300× slower to check.) -/
theorem exec (op : UInt8) : Sim (CPU.exec (σ := NES) op) (CPU.exec (σ := Plain) op) := by
  obtain ⟨⟨⟨n, hn⟩⟩⟩ := op
  match n, hn with
{arms}
  | n + 256, h => exact absurd h (by omega)

end Smb.Sim
''')
print('\n'.join(out))
